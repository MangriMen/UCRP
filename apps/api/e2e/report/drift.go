package report

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"sync"
)

type Drift struct {
	Requirement string
	Operation   string
	Detail      string
}

type DriftLog struct {
	mu      sync.Mutex
	entries map[string]Drift
}

var Drifts = &DriftLog{entries: map[string]Drift{}}

func (d *DriftLog) Record(requirement, operation, detail string) {
	d.mu.Lock()
	defer d.mu.Unlock()
	key := requirement + "|" + operation + "|" + detail
	d.entries[key] = Drift{Requirement: requirement, Operation: operation, Detail: detail}
}

func (d *DriftLog) All() []Drift {
	d.mu.Lock()
	defer d.mu.Unlock()
	out := make([]Drift, 0, len(d.entries))
	for _, e := range d.entries {
		out = append(out, e)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Requirement != out[j].Requirement {
			return out[i].Requirement < out[j].Requirement
		}
		return out[i].Operation < out[j].Operation
	})
	return out
}

func (d *DriftLog) WriteMarkdown(path string) error {
	entries := d.All()
	var b strings.Builder
	b.WriteString("# Contract drift observed during the E2E run\n\n")
	b.WriteString("Generated by `apps/api/e2e`. Each row is a place where the running API\n")
	b.WriteString("does not match the bundled OpenAPI contract. The contract was not modified.\n\n")
	if len(entries) == 0 {
		b.WriteString("No drift detected.\n")
	} else {
		b.WriteString("| Requirement | Operation | Divergence |\n| --- | --- | --- |\n")
		for _, e := range entries {
			fmt.Fprintf(&b, "| %s | `%s` | %s |\n", e.Requirement, e.Operation, e.Detail)
		}
	}
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write drift report %s: %w", path, err)
	}
	return nil
}
